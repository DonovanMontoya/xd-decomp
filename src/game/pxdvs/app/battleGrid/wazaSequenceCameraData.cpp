CameraPatternRow* wazaSequenceCameraGetPattern(bool attack, int flags) {
    f32 value = HSD_Randf();
    f32 total = 0.0f;
    CameraPatternRow* row;
    int count;
    if (attack) {
        count = 8;
        row = attackPatterns;
        if (flags & 0x80) {
            return row + 4;
        }
        if (flags & 0x100) {
            return row + 5;
        }
        if (flags & 0x200) {
            return row + 6;
        }
    } else {
        count = 13;
        row = defensePatterns;
        if (flags & 0x80) {
            return row + 9;
        }
        if (flags & 0x100) {
            return row + 10;
        }
        if (flags & 0x200) {
            return row + 11;
        }
    }
    for (int i = 0; i < count; i++) {
        total += row->word[0].value;
        if (value < total) {
            return row;
        }
        row++;
    }
    if (attack) {
        u32 low = HSD_Rand();
        u32 high = HSD_Rand();
        return attackPatterns + (((high << 16) | low) & 7);
    }
    u32 low = HSD_Rand();
    u32 high = HSD_Rand();
    return defensePatterns + (((high << 16) | low) % 13);
}
